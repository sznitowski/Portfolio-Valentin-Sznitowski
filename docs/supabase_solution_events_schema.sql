-- 1. Create table public.solution_events
CREATE TABLE IF NOT EXISTS public.solution_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  event_type TEXT NOT NULL CHECK (event_type IN ('solution_view', 'solution_cta_click')),
  solution_slug TEXT NOT NULL CHECK (solution_slug IN ('tradesquote', 'checklist-rapido', 'cleanroute', 'truckstock-lite')),
  source TEXT,
  utm_source TEXT,
  utm_medium TEXT,
  utm_campaign TEXT,
  utm_content TEXT
);

-- 2. Indexes for fast aggregation and temporal filtering
CREATE INDEX IF NOT EXISTS idx_solution_events_created_at ON public.solution_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_solution_events_slug ON public.solution_events (solution_slug);
CREATE INDEX IF NOT EXISTS idx_solution_events_type ON public.solution_events (event_type);

-- 3. Row Level Security & Anon Grants
ALTER TABLE public.solution_events ENABLE ROW LEVEL SECURITY;

GRANT ALL ON public.solution_events TO anon;
GRANT ALL ON public.solution_events TO authenticated;

-- Allow anon to INSERT
DROP POLICY IF EXISTS "allow anon insert solution events" ON public.solution_events;
CREATE POLICY "allow anon insert solution events"
  ON public.solution_events
  FOR INSERT
  TO anon
  WITH CHECK (true);

-- Deny anon direct SELECT (RLS blocks raw event scraping, returns 0 rows)
DROP POLICY IF EXISTS "deny anon select solution events" ON public.solution_events;
CREATE POLICY "deny anon select solution events"
  ON public.solution_events
  FOR SELECT
  TO anon
  USING (false);

-- 4. Secure Aggregation RPC (Returns Commercial Totals Excluding internal_test)
CREATE OR REPLACE FUNCTION public.get_commercial_signals_summary()
RETURNS TABLE (
  solution_slug TEXT,
  views BIGINT,
  cta_clicks BIGINT,
  ctr NUMERIC
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  WITH event_counts AS (
    SELECT
      e.solution_slug,
      COUNT(CASE WHEN e.event_type = 'solution_view' THEN 1 END) AS v_count,
      COUNT(CASE WHEN e.event_type = 'solution_cta_click' THEN 1 END) AS c_count
    FROM public.solution_events e
    WHERE (e.utm_campaign IS NULL OR e.utm_campaign != 'internal_test')
    GROUP BY e.solution_slug
  ),
  catalog AS (
    SELECT unnest(ARRAY['tradesquote', 'checklist-rapido', 'cleanroute', 'truckstock-lite']) AS slug
  )
  SELECT
    c.slug AS solution_slug,
    COALESCE(ec.v_count, 0)::BIGINT AS views,
    COALESCE(ec.c_count, 0)::BIGINT AS cta_clicks,
    CASE
      WHEN COALESCE(ec.v_count, 0) > 0 THEN
        ROUND((COALESCE(ec.c_count, 0)::NUMERIC / ec.v_count::NUMERIC) * 100, 2)
      ELSE 0.00
    END AS ctr
  FROM catalog c
  LEFT JOIN event_counts ec ON ec.solution_slug = c.slug
  ORDER BY c.slug;
END;
$$;

GRANT EXECUTE ON FUNCTION public.get_commercial_signals_summary() TO anon;
GRANT EXECUTE ON FUNCTION public.get_commercial_signals_summary() TO authenticated;

