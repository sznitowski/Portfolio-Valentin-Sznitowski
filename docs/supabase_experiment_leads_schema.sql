-- 1. Create table with exact database contract
CREATE TABLE IF NOT EXISTS public.experiment_leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    email TEXT NOT NULL,
    trade TEXT DEFAULT 'other',
    opportunity_slug TEXT DEFAULT 'contractors-quote_to_invoice' NOT NULL,
    variant TEXT DEFAULT 'a',
    utm_source TEXT DEFAULT 'direct',
    utm_medium TEXT DEFAULT 'none',
    utm_campaign TEXT,
    utm_content TEXT,
    CONSTRAINT unique_opportunity_email UNIQUE (opportunity_slug, email)
);

-- 2. Indexes for fast lookup & reporting
CREATE INDEX IF NOT EXISTS idx_experiment_leads_slug ON public.experiment_leads(opportunity_slug);
CREATE INDEX IF NOT EXISTS idx_experiment_leads_variant ON public.experiment_leads(variant);
CREATE INDEX IF NOT EXISTS idx_experiment_leads_created_at ON public.experiment_leads(created_at DESC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.experiment_leads ENABLE ROW LEVEL SECURITY;

-- 4. Security Policy: Allow anon INSERT from Next.js Server Action / REST API
-- Drops existing policies if re-running
DROP POLICY IF EXISTS "Allow anon insert experiment_leads" ON public.experiment_leads;
CREATE POLICY "Allow anon insert experiment_leads" 
ON public.experiment_leads 
FOR INSERT 
TO anon 
WITH CHECK (true);

-- 5. Security Policy: Deny anon direct SELECT (protects lead emails from public scrapers)
DROP POLICY IF EXISTS "Deny anon select experiment_leads" ON public.experiment_leads;
CREATE POLICY "Deny anon select experiment_leads" 
ON public.experiment_leads 
FOR SELECT 
TO anon 
USING (false);

